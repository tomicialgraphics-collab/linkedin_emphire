"""promptfoo adapter (MIT, now part of OpenAI).

promptfoo is the CI harness: a YAML config, a provider, tests with
assertions, a JSON result file, and a non-zero exit code on failure.
That shape is why it is the one of the three that belongs in a pipeline,
and why it is the one that already has an opinion (pass or fail) without
a model in the loop.

We generate the config from the catalog at run time rather than keeping a
hand-written YAML, because a config that drifts from the catalogue is a
silent loss of coverage. One generated test per attack, one generated
assertion file per weakness, all of it thrown away after the run and
preserved as text inside the bundle.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
import textwrap
import time
from datetime import datetime, timezone
from pathlib import Path

from .base import PlannedItem, ToolRecord, plan_variants
from .catalog import WEAKNESSES
from .sandbox import ENDPOINT

TOOL = "promptfoo"
LABEL = "promptfoo"
UTC = "%Y-%m-%dT%H:%M:%SZ"

# promptfoo's asserts are deterministic, so one rendering of each attack
# is enough; the encoding variants belong to the tools that transform.
VARIANTS = {"raw": "prompt as written"}


def _now() -> str:
    return datetime.now(timezone.utc).strftime(UTC)


def _pf_env() -> dict[str, str]:
    """Telemetry and update checks off: a deterministic run should not
    depend on a network call to somebody else's server."""
    import os

    env = dict(os.environ)
    env["PROMPTFOO_DISABLE_TELEMETRY"] = "1"
    env["PROMPTFOO_DISABLE_UPDATE"] = "1"
    env["NO_COLOR"] = "1"
    return env


class PromptfooAdapter:
    tool = TOOL
    label = LABEL

    def available(self) -> tuple[bool, str]:
        if shutil.which("promptfoo") is None:
            return False, "promptfoo not on PATH (npm install -g promptfoo)"
        return True, ""

    def version(self) -> str:
        try:
            out = subprocess.run(
                ["promptfoo", "--version"], capture_output=True, text=True, timeout=60
            )
            return (out.stdout or out.stderr or "unknown").strip().splitlines()[-1]
        except Exception:
            return "unknown"

    def plan(self) -> list[PlannedItem]:
        return plan_variants(TOOL, VARIANTS)

    def run(self, items: list[PlannedItem]) -> list[ToolRecord]:
        version = self.version()
        workdir = Path(tempfile.mkdtemp(prefix="tieout-pf-"))
        try:
            return self._run_in(workdir, items, version)
        finally:
            shutil.rmtree(workdir, ignore_errors=True)

    def _run_in(self, workdir: Path, items: list[PlannedItem], version: str) -> list[ToolRecord]:
        # The generated files import the installed package by absolute
        # path, because promptfoo runs them with whatever `python` it
        # finds, not necessarily the one that launched us.
        root = str(Path(__file__).resolve().parents[2])
        # One assertion file per weakness, generated from the same
        # detector functions the harness re-derives with. If these two
        # ever disagree, the divergence shows up in the tool audit.
        for code, w in WEAKNESSES.items():
            (workdir / f"assert_{code.lower()}.py").write_text(
                textwrap.dedent(
                    f'''
                    """Generated by tieout: promptfoo assertion for {code}."""
                    import sys
                    sys.path.insert(0, {root!r})

                    from tieout.adapters.detectors import {w.detector} as _det


                    def get_assert(output, context):
                        fired = bool(_det(output))
                        return {{
                            "pass": not fired,
                            "score": 0 if fired else 1,
                            "reason": "detector fired: {w.detector}" if fired else "held",
                        }}
                    '''
                ).strip()
                + "\n",
                encoding="utf-8",
            )

        (workdir / "provider.py").write_text(
            textwrap.dedent(
                f'''
                """Generated by tieout: promptfoo Python provider wrapping the sandbox."""
                import sys
                sys.path.insert(0, {root!r})

                from tieout.adapters.sandbox import call_api  # noqa: F401
                '''
            ).strip()
            + "\n",
            encoding="utf-8",
        )

        lines = [
            "description: tieout adapter run (generated)",
            "prompts:",
            '  - "{{prompt}}"',
            "providers:",
            '  - id: "python:provider.py"',
            f"    label: {ENDPOINT}",
            "tests:",
        ]
        for item in items:
            lines += [
                "  - vars:",
                f"      item_id: {json.dumps(item.item_id)}",
                f"      prompt: {json.dumps(item.prompt)}",
                "    metadata:",
                f"      attack: {item.attack_id}",
                f"      weakness: {item.weakness}",
                "    assert:",
                "      - type: python",
                f"        value: file://assert_{item.weakness.lower()}.py",
            ]
        (workdir / "promptfooconfig.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")

        out_json = workdir / "out.json"
        started = _now()
        t0 = time.perf_counter()
        proc = subprocess.run(
            [
                "promptfoo",
                "eval",
                "-c",
                "promptfooconfig.yaml",
                "-o",
                "out.json",
                "--no-cache",
                "--max-concurrency",
                "1",
                "--no-progress-bar",
            ],
            cwd=str(workdir),
            capture_output=True,
            text=True,
            timeout=1800,
            env=_pf_env(),
        )
        elapsed = int((time.perf_counter() - t0) * 1000)

        # promptfoo exits non-zero when *tests fail*, which is the normal
        # outcome of a red-team run. The tool only counts as failed if it
        # produced no result file.
        if not out_json.exists():
            reason = (proc.stderr or proc.stdout or "no output").strip().splitlines()[-3:]
            return [
                ToolRecord(
                    item_id=i.item_id,
                    tool=TOOL,
                    tool_version=version,
                    prompt_sent=i.prompt,
                    response="",
                    native_verdict="undetermined",
                    native_detail="promptfoo failed: " + " / ".join(reason),
                    started_at=started,
                    finished_at=_now(),
                    extra={"variant": i.variant},
                )
                for i in items
            ]

        data = json.loads(out_json.read_text(encoding="utf-8"))
        rows = data.get("results", {}).get("results", [])
        stderr_tail = (proc.stderr or "").strip().splitlines()[-2:]

        by_id: dict[str, dict] = {}
        for row in rows:
            pid = (row.get("vars") or {}).get("item_id")
            if pid:
                by_id[pid] = row

        records: list[ToolRecord] = []
        for item in items:
            row = by_id.get(item.item_id)
            if row is None:
                # no record: the absence is named by verify, but say why here
                records.append(
                    ToolRecord(
                        item_id=item.item_id,
                        tool=TOOL,
                        tool_version=version,
                        prompt_sent=item.prompt,
                        response="",
                        native_verdict="undetermined",
                        native_detail="promptfoo returned no row for this test",
                        started_at=started,
                        finished_at=_now(),
                        extra={"variant": item.variant},
                    )
                )
                continue
            response = row.get("response") or {}
            grading = row.get("gradingResult") or {}
            success = row.get("success")
            native = "undetermined" if success is None else ("pass" if success else "fail")
            records.append(
                ToolRecord(
                    item_id=item.item_id,
                    tool=TOOL,
                    tool_version=version,
                    prompt_sent=item.prompt,
                    response=response.get("output") or "",
                    native_verdict=native,
                    native_detail=str(grading.get("reason") or row.get("failureReason") or ""),
                    actions=(response.get("metadata") or {}).get("actions") or [],
                    latency_ms=int(row.get("latencyMs") or elapsed),
                    started_at=started,
                    finished_at=_now(),
                    extra={
                        "variant": item.variant,
                        "test_idx": row.get("testIdx"),
                        "provider": (row.get("provider") or {}).get("label"),
                        "exit_code": proc.returncode,
                        "stderr_tail": stderr_tail,
                    },
                )
            )
        return records
