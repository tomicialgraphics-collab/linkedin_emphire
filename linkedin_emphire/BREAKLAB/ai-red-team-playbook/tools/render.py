#!/usr/bin/env python3
"""Render the printable and spreadsheet forms of the checklist.

Input:  checklist/checklist.json   (the source of truth)
Output: checklist/CHECKLIST.md     (printable, one line per test)
        checklist/checklist.csv    (for a tracker or a spreadsheet)

The rendered files are committed so that the repository is readable without
running anything. CI re-renders and fails if the output has drifted from the
source, which is the only reliable way to stop the two diverging.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "checklist" / "checklist.json"
MD_OUT = ROOT / "checklist" / "CHECKLIST.md"
CSV_OUT = ROOT / "checklist" / "checklist.csv"

TIER_NOTE = {
    "core": "run these from memory",
    "standard": "run when the target has them",
    "extended": "recognise the name, know the limitation",
}


def load() -> dict:
    with SOURCE.open(encoding="utf-8") as fh:
        return json.load(fh)


def render_markdown(data: dict) -> str:
    items = data["items"]
    core = sum(1 for i in items if i["tier"] == "core")

    lines = [
        "# The checklist",
        "",
        f"Generated from `checklist.json` by `tools/render.py`. {len(items)} items, "
        f"{len(data['categories'])} categories, {core} of them in the core tier. Do not edit this file by hand.",
        "",
        "Mark each line once per engagement as one of **tested**, **absent** (the target does not have it), "
        "**skipped** (deliberately not tested, with a reason) or **open**. The third and fourth columns of a "
        "coverage argument come from this sheet, and both belong in the report.",
        "",
        "| Tier | Meaning |",
        "|---|---|",
    ]
    for tier, note in TIER_NOTE.items():
        lines.append(f"| `{tier}` | {note} |")

    for cat in data["categories"]:
        group = [i for i in items if i["category"] == cat["slug"]]
        lines += [
            "",
            f"## {cat['label']}  ({len(group)})",
            "",
            f"*{cat['blurb']}*",
            "",
        ]
        for item in group:
            lines.append(f"- [ ] **{item['id']}** {item['name']} (`{item['tier']}`)  ")
            lines.append(f"      {item['test']}")

    lines += [
        "",
        "---",
        "",
        "## While you are in there",
        "",
        "- [ ] A canary string is planted in the system prompt and searched for in outputs and logs.",
        "- [ ] The model revision, prompt version, index snapshot, tool schema, sampling settings and date are recorded.",
        "- [ ] The last finding has a case in the suite that runs on every deploy.",
        "",
    ]
    return "\n".join(lines)


def render_csv(data: dict) -> str:
    cats = {c["slug"]: c["label"] for c in data["categories"]}
    import io

    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["id", "category", "category_label", "name", "tier", "test", "status", "note"])
    for item in data["items"]:
        writer.writerow([
            item["id"],
            item["category"],
            cats.get(item["category"], ""),
            item["name"],
            item["tier"],
            item["test"],
            "",
            "",
        ])
    return buf.getvalue()


def main() -> int:
    ap = argparse.ArgumentParser(description="render CHECKLIST.md and checklist.csv")
    ap.add_argument("--check", action="store_true", help="fail if the rendered files are out of date")
    args = ap.parse_args()

    data = load()
    rendered = {MD_OUT: render_markdown(data), CSV_OUT: render_csv(data)}

    if args.check:
        stale = [p for p, text in rendered.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"STALE  {path.relative_to(ROOT)}")
        if stale:
            print("\nrun: python3 tools/render.py")
            return 1
        print("OK  rendered files match the source")
        return 0

    for path, text in rendered.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
